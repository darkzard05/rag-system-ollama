def _route_of(weights: dict[str, float]) -> str:
    if weights == {"bm25": 0.8, "faiss": 0.2}:
        return "keyword"
    if weights == {"bm25": 0.2, "faiss": 0.8}:
        return "semantic"
    return "both"


def _newest_repro_report() -> Path:
    """Newest corrected repro report (glob newest-wins)."""
    candidates = sorted(ROOT.glob("reports/repro_h3_weights_2026*.md"))
    assert candidates, "no repro_h3_weights report found"
    return candidates[-1]


def _report_row_weights(report: Path) -> dict[str, list[float]]:
    """Parse per-row claimed Weights [BM25,FAISS] keyed by row id."""
    claimed: dict[str, list[float]] = {}
    for line in report.read_text(encoding="utf-8").splitlines():
        row_match = _ROW_RE.match(line)
        if not row_match:
            continue
        weight_match = _WEIGHT_RE.search(line)
        assert weight_match, f"row without weights cell: {line[:60]}"
        claimed[row_match.group(1)] = [
            float(weight_match.group(1)),
            float(weight_match.group(2)),
        ]
    return claimed


async def test_report_blend_rows_reproducible() -> None:
    """(a) GREEN: dual-match rows emit code-enumerated weights matching the report."""
    # F1-3/F1-4: keyword branch emits 0.8; F1-6/F1-7: semantic branch emits
    # 0.8; F1-9: grep 0.6 has no hits in the dynamic path; F1-10: static
    # default ensemble_weights is [0.4, 0.6]. BLEND_DECISION (strict 3-way):
    # the real path can only emit [0.4,0.6]/[0.8,0.2]/[0.2,0.8].
    assert DYNAMIC_WEIGHTING_CONFIG.get("keyword_weight") == 0.8  # F1-3
    assert DYNAMIC_WEIGHTING_CONFIG.get("semantic_weight") == 0.8  # F1-6
    assert list(ENSEMBLE_WEIGHTS) == [0.4, 0.6]  # F1-10
    report = _newest_repro_report()
    text = report.read_text(encoding="utf-8")
    assert "[0.6, 0.4]" not in text, f"{report.name} still contains a blend"
    assert "[0.6,0.4]" not in text, f"{report.name} still contains a blend"
    claimed = _report_row_weights(report)
    for row_id, question in BLEND_ROWS:
        weights = await _real_weights(question)
        pair = [weights["bm25"], weights["faiss"]]
        assert pair != [0.6, 0.4], f"{row_id}: impossible blend regressed: {weights}"
        assert tuple(pair) in CODE_ENUMERATED, (
            f"{row_id}: {weights} outside code-enumerated set {sorted(CODE_ENUMERATED)}"
        )
        assert pair == claimed[row_id], (
            f"{row_id}: real path {pair} != report row {claimed[row_id]}"
        )


async def test_misroute_zero_of_twelve_reproducible() -> None:
    """(b) GREEN: PARTIAL-included rate is the corrected 4/12; 2869337 reconciled."""
    # The defective report claimed "Misrouted: 0/12" with PARTIAL rows
    # excluded. Corrected measurement (BLEND_DECISION, strict 3-way,
    # denominator == row count): the 4 dual-match rows fall back to the
    # static default [0.4, 0.6] (both-signal, matches neither pure route).
    misrouted = 0
    total = 0
    for _row_id, question, expected in REPRO_MATRIX:
        weights = await _real_weights(question)
        total += 1
        if _route_of(weights) != expected:
            misrouted += 1
    assert total == 12, f"matrix row count changed: {total}"
    assert (misrouted, total) == (4, 12), (
        f"corrected rate is 4/12, got {misrouted}/{total}"
    )
    # NOTE (deletion reason): the RED revision ended with a hardcoded
    # `assert True != True` tautology (report_admits_misroute /
    # commit_claims_zero literals) that could never pass by construction, so
    # it proved nothing about the code or the record. Replaced with a check
    # against the real follow-up note reconciling commit 2869337.
    note = ROOT / "reports" / "f1_2869337_followup_note.md"
    assert note.is_file(), "2869337 follow-up note missing (no history rewrite)"
    assert "4/12" in note.read_text(encoding="utf-8"), (
        "follow-up note must carry the corrected 4/12 rate"
    )


