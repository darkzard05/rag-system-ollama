async def _real_weights(query: str) -> dict[str, float]:
    """Drive the real preprocess weight path (F1-1..F1-8)."""
    state = {"input": query}
    config = {"configurable": {}}
    result = await preprocess(state, config, writer=MockWriter())
    return result["search_weights"]


